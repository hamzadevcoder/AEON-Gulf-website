/** Look up a message and fill its {placeholders}. Unknown keys are returned as-is (so plain text passes through). */
export function translate(messages: Messages, key: string, vars?: Record<string, string | number>) {
  const s = messages[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}
